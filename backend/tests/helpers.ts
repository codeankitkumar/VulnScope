import request from 'supertest';
import { getDb } from '../src/db/index.js';
import { createApp } from '../src/app.js';
import type { PublicUser } from '../src/types/index.js';

export const app = createApp();

export async function createUser(overrides?: Partial<{ email: string; password: string; name: string; role: PublicUser['role'] }>): Promise<PublicUser> {
  const email = overrides?.email ?? `u${Date.now()}${Math.floor(Math.random() * 1000)}@test.local`;
  const password = overrides?.password ?? 'Password123!';
  const res = await request(app)
    .post('/api/auth/register')
    .send({ email, password, name: overrides?.name ?? 'Test User' })
    .expect(201);
  const user = res.body.user as PublicUser;
  if (overrides?.role === 'admin') {
    await getDb()('users').where({ id: user.id }).update({ role: 'admin' });
  }
  return { ...user, role: (overrides?.role as PublicUser['role']) ?? user.role };
}

export async function authToken(password = 'Password123!'): Promise<string> {
  const user = await createUser({ password });
  const res = await request(app).post('/api/auth/login').send({ email: user.email, password }).expect(200);
  return res.body.token as string;
}

export async function createProject(token: string, name = 'Test Project'): Promise<string> {
  const res = await request(app)
    .post('/api/projects')
    .set('Authorization', `Bearer ${token}`)
    .send({ name, description: 'generated by tests' })
    .expect(201);
  return res.body.project.id as string;
}

export async function createTarget(token: string, projectId: string, overrides?: Record<string, unknown>): Promise<Record<string, unknown>> {
  const res = await request(app)
    .post('/api/targets')
    .set('Authorization', `Bearer ${token}`)
    .send({ projectId, name: 'target-' + Math.floor(Math.random() * 1e6), kind: 'web', host: 'https://example.com', ...overrides })
    .expect(201);
  return res.body.target as Record<string, unknown>;
}

/** Fully ready a target for scanning: generate token, verify, allowlist via API. */
export async function prepareTargetForScan(token: string, targetId: string): Promise<void> {
  const gen = await request(app)
    .post(`/api/targets/${targetId}/ownership-token`)
    .set('Authorization', `Bearer ${token}`)
    .expect(200);
  const ownershipToken = gen.body.ownershipToken as string;
  await request(app)
    .post(`/api/targets/${targetId}/verify`)
    .set('Authorization', `Bearer ${token}`)
    .send({ ownershipToken, ownershipOwner: 'owner@customer.local' })
    .expect(200);
  await request(app)
    .put(`/api/targets/${targetId}/allowlist`)
    .set('Authorization', `Bearer ${token}`)
    .send({ allowlisted: true })
    .expect(200);
}
